function pick(claim) {
  const s = (claim || '').toLowerCase();
  if (/owner|founder/.test(s)) return 'owner';
  if (/bbb|accredit|a\+|rated|rating|reviews?/.test(s)) return 'badge';
  if (/licen|insur|bond|local|warrant|guarantee/.test(s)) return 'shield';
  if (/hail|wind|ice|snow|storm|weather|climate|minnesota|\bmn\b|season/.test(s)) return 'weather';
  if (/\byears?\b|experience|\bexp\b|decade/.test(s)) return 'medal';
  if (/roof|siding|window|gutter|exterior|one.?stop|full/.test(s)) return 'house';
  if (/franchise|call ?center/.test(s)) return 'people';
  if (/base|joint|prep|craft|clean|install/.test(s)) return 'tool';
  if (/free|estimate|quote|honest|price|no.?cost/.test(s)) return 'estimate';
  return 'spark';
}

